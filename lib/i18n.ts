const LANG_STORAGE_KEY = "brandpulse_language";
const LANG_CHANGE_EVENT = "brandpulse_lang_change";

export function getStoredLanguage(): Language {
  if (typeof window === "undefined") return "en";
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY) as Language;
    if (SUPPORTED_LANGUAGES.some((opt) => opt.code === saved)) return saved;
  } catch {
    // ignore
  }
  return "en";
}

export function setStoredLanguage(lang: Language): void {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
    window.dispatchEvent(new CustomEvent(LANG_CHANGE_EVENT, { detail: lang }));
  } catch {
    // ignore
  }
}

export function useLanguage(): {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: keyof typeof translations.en) => string;
} {
  const [language, setLanguageState] = useState<Language>("en");

  useEffect(() => {
    setLanguageState(getStoredLanguage());

    const handleCustomChange = (e: Event) => {
      const detail = (e as CustomEvent<Language>).detail;
      if (SUPPORTED_LANGUAGES.some((opt) => opt.code === detail)) {
        setLanguageState(detail);
      }
    };

    window.addEventListener(LANG_CHANGE_EVENT, handleCustomChange);
    return () => {
      window.removeEventListener(LANG_CHANGE_EVENT, handleCustomChange);
    };
  }, []);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    setStoredLanguage(lang);
  };

  const t = (key: keyof typeof translations.en): string => {
    const dict = translations[language] || translations.en;
    return dict[key] || translations.en[key] || key;
  };

  return { language, setLanguage, t };
}
